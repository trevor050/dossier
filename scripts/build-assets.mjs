// Bundles everything the server serves to browsers into two generated TS modules:
//   src/generated/client-assets.ts  tracker script + lazy recorder/fingerprint chunks (served by /api/collect)
//   src/generated/admin-assets.ts   dashboard app, styles and replay player (served by /api/admin)
// Usage: node scripts/build-assets.mjs [--if-missing]
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/generated');
const clientOut = join(out, 'client-assets.ts');
const adminOut = join(out, 'admin-assets.ts');

if (process.argv.includes('--if-missing') && existsSync(clientOut) && existsSync(adminOut) && existsSync(join(root, 'dashboard/world.gen.ts'))) process.exit(0);
mkdirSync(out, { recursive: true });

// World land outline, projected once at build time (equirectangular, 1000x500).
const land = JSON.parse(readFileSync(join(root, 'node_modules/world-atlas/land-110m.json'), 'utf8'));
const projection = geoEquirectangular().scale(1000 / (2 * Math.PI)).translate([500, 250]);
const worldPath = geoPath(projection)(feature(land, land.objects.land))
  .replace(/(\d+\.\d)\d+/g, '$1');
writeFileSync(join(root, 'dashboard/world.gen.ts'), `// Generated by scripts/build-assets.mjs from world-atlas (Natural Earth, public domain).\nexport const WORLD_PATH = ${JSON.stringify(worldPath)};\n`);

const common = { bundle: true, minify: true, write: false, legalComments: 'none', logLevel: 'warning' };

async function bundle(entry, extra = {}) {
  const res = await build({ ...common, entryPoints: [join(root, entry)], ...extra });
  return res.outputFiles.map((f) => ({ path: f.path, text: f.text }));
}

const js = 'text/javascript; charset=utf-8';
const css = 'text/css; charset=utf-8';

function asset(type, body) {
  return { type, body, hash: createHash('sha256').update(body).digest('hex').slice(0, 12) };
}

function emit(file, name, assets) {
  const lines = [
    '// Generated by scripts/build-assets.mjs. Do not edit.',
    `export const ${name}: Record<string, { type: string; body: string; hash: string }> = {`,
    ...Object.entries(assets).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
    '};',
    '',
  ];
  writeFileSync(file, lines.join('\n'));
}

const browser = { platform: 'browser', target: ['es2020', 'safari15'], format: 'iife' };

const [tracker] = await bundle('src/chunks/tracker.ts', browser);
const [recorder] = await bundle('src/chunks/recorder.ts', browser);
const [fingerprint] = await bundle('src/chunks/fingerprint.ts', browser);
emit(clientOut, 'CLIENT_ASSETS', {
  'tracker.js': asset(js, tracker.text),
  'recorder.js': asset(js, recorder.text),
  'fingerprint.js': asset(js, fingerprint.text),
});

const app = await bundle('dashboard/main.tsx', {
  platform: 'browser',
  target: ['es2020'],
  format: 'esm',
  jsx: 'automatic',
  jsxImportSource: 'preact',
  outdir: join(root, '.local/dash'),
  loader: { '.css': 'css' },
});
const player = await bundle('dashboard/player.ts', {
  platform: 'browser',
  target: ['es2020'],
  format: 'iife',
  outdir: join(root, '.local/player'),
  loader: { '.css': 'css' },
});
const pick = (files, ext) => files.find((f) => f.path.endsWith(ext))?.text ?? '';
emit(adminOut, 'ADMIN_ASSETS', {
  'app.js': asset(js, pick(app, '.js')),
  'app.css': asset(css, pick(app, '.css')),
  'player.js': asset(js, pick(player, '.js')),
  'player.css': asset(css, pick(player, '.css')),
});

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`;
console.log(
  `assets: tracker ${kb(tracker.text)}, recorder ${kb(recorder.text)}, fingerprint ${kb(fingerprint.text)}, ` +
    `dashboard ${kb(pick(app, '.js'))} + ${kb(pick(app, '.css'))} css, player ${kb(pick(player, '.js'))}`,
);
